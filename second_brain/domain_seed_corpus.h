// chain.
//
// It exists to make the scaling of the learned structures measurable:
//
//   * the shipped bootstrap corpus registers 10 node entities in 20
//     declarative lines, and the constructor used to feed only the first 20
//     declarative lines to the cluster discovery -- the entity vocabulary was
//     therefore capped at whatever 20 lines could register. This corpus
//     registers 32, so the cap is visible: with the cap the vocabulary stops
//     at 20, without it the vocabulary follows the corpus.
//
//   * the anchors (the prototype trajectories a question is routed to) and the
//     causal graph are learned from this text, not hard-coded.
//
// The corpus states its graph the way a human would:
//
//     "... : <A> -> <B> -> <C> -> <D> ."
//
// which the engine parses out of the think section of a supervised line.
//
// Structural note: the declarative lines deliberately keep the SAME frames as
// the shipped corpus -- ("<role word>", "<next word>") -- so the engine
